  FOREACH role_name IN ARRAY ARRAY['invoice_app','invoice_test'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
      IF role_name = 'invoice_app' THEN
        GRANT SELECT ON TABLE settings TO invoice_app;
      END IF;
      FOREACH table_name IN ARRAY base_tables LOOP
        IF role_name = 'invoice_app' THEN
          EXECUTE format('GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE %I TO %I',
                         table_name,role_name);
        ELSE
          EXECUTE format('GRANT ALL PRIVILEGES ON TABLE %I TO %I',table_name,role_name);
        END IF;
        sequence_name := pg_get_serial_sequence(table_name,'id');
        IF sequence_name IS NOT NULL THEN
          EXECUTE format('GRANT USAGE,SELECT ON SEQUENCE %s TO %I',sequence_name,role_name);
        END IF;
      END LOOP;
    END IF;
  END LOOP;
