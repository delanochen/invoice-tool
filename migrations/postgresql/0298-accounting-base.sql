    EXECUTE format('CREATE TRIGGER %I BEFORE INSERT OR UPDATE OR DELETE ON %I '
                   'FOR EACH ROW EXECUTE FUNCTION protect_posted_voucher_child()',
                   table_name || '_protect_posted', table_name);
