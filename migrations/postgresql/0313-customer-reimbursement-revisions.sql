BEGIN;

-- 0313：工单结算「一份结算、多个修订版本」。
--
-- 业务规则（2026-10-17 用户拍板）：
--   * 工单保留一个结算入口，默认展示「当前有效版本」，可查看历史版本；
--   * 创建修订版时从原版本复制完整快照（明细 / 费率 / 报销关联 / 原报销金额 /
--     客户结算金额 / 不计入确认 / 附件），不自动重读最新来源；
--   * 新版本仍是草稿或审核期间，原版本继续有效；新版本审核通过并确认替代后，
--     原版本标记 superseded 且只读，原始 PDF / 附件 / 审核 / 发送记录保留；
--   * 结算统计、开票、利润表只读当前有效版本，各版本金额不得累加；
--   * 同一报销明细可出现在同一系列的不同版本，禁止在其他独立结算重复计费；
--   * 存量结算各自成为 V1；同工单只允许一个 is_current。

CREATE TABLE IF NOT EXISTS public.customer_reimbursement_series (
    id bigint NOT NULL,
    service_order_id bigint NOT NULL,
    created_at text NOT NULL,
    legacy_settlement_id bigint
);

ALTER TABLE public.customer_reimbursement_series
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.customer_reimbursement_series_id_seq
        START WITH 1
        INCREMENT BY 1
        NO MINVALUE
        NO MAXVALUE
        CACHE 1
    );

ALTER TABLE ONLY public.customer_reimbursement_series
    DROP CONSTRAINT IF EXISTS customer_reimbursement_series_pkey;
ALTER TABLE ONLY public.customer_reimbursement_series
    ADD CONSTRAINT customer_reimbursement_series_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.customer_reimbursement_series
    DROP CONSTRAINT IF EXISTS customer_reimbursement_series_service_order_id_fkey;
ALTER TABLE ONLY public.customer_reimbursement_series
    ADD CONSTRAINT customer_reimbursement_series_service_order_id_fkey
    FOREIGN KEY (service_order_id) REFERENCES public.service_orders(id) ON DELETE CASCADE;

CREATE UNIQUE INDEX IF NOT EXISTS uq_customer_reimbursement_series_legacy
    ON public.customer_reimbursement_series (legacy_settlement_id)
    WHERE legacy_settlement_id IS NOT NULL;

ALTER TABLE public.customer_reimbursements
    ADD COLUMN IF NOT EXISTS series_id bigint;
ALTER TABLE public.customer_reimbursements
    ADD COLUMN IF NOT EXISTS version_no integer NOT NULL DEFAULT 1;
ALTER TABLE public.customer_reimbursements
    ADD COLUMN IF NOT EXISTS supersedes_id bigint;
ALTER TABLE public.customer_reimbursements
    ADD COLUMN IF NOT EXISTS is_current boolean NOT NULL DEFAULT false;
ALTER TABLE public.customer_reimbursements
    ADD COLUMN IF NOT EXISTS revision_reason text NOT NULL DEFAULT '';
ALTER TABLE public.customer_reimbursements
    ADD COLUMN IF NOT EXISTS superseded_at text;
-- sources_frozen：修订版草稿不再自动合并日报 / 报销来源，只按快照重算汇总。
ALTER TABLE public.customer_reimbursements
    ADD COLUMN IF NOT EXISTS sources_frozen boolean NOT NULL DEFAULT false;

-- ── 存量回填：每张现有结算自成系列 V1 ────────────────────────────
-- legacy_settlement_id 只用于回填关联，回填后即无新值写入。
INSERT INTO public.customer_reimbursement_series (service_order_id, created_at, legacy_settlement_id)
SELECT cr.service_order_id, cr.created_at, cr.id
FROM public.customer_reimbursements cr
WHERE NOT EXISTS (
    SELECT 1 FROM public.customer_reimbursement_series s WHERE s.legacy_settlement_id = cr.id
);

UPDATE public.customer_reimbursements cr
SET series_id = s.id
FROM public.customer_reimbursement_series s
WHERE s.legacy_settlement_id = cr.id AND cr.series_id IS NULL;

UPDATE public.customer_reimbursements SET version_no = 1 WHERE version_no IS NULL;
UPDATE public.customer_reimbursements SET is_current = false;
-- 同工单只保留「最新一张」为当前有效版本；其余草稿在语义上本就已被 latest_ 遮蔽。
UPDATE public.customer_reimbursements cr
SET is_current = true
WHERE cr.id IN (
    SELECT DISTINCT ON (service_order_id) id
    FROM public.customer_reimbursements
    ORDER BY service_order_id, created_at DESC, id DESC
);

ALTER TABLE public.customer_reimbursements
    ALTER COLUMN series_id SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_customer_reimbursement_current_per_order
    ON public.customer_reimbursements (service_order_id) WHERE is_current;

CREATE INDEX IF NOT EXISTS idx_customer_reimbursement_series_version
    ON public.customer_reimbursements (series_id, version_no);

-- 修订版必须能从被替代版本取回上下文：替代后旧行仍在，外键 RESTRICT 防止误删。
ALTER TABLE ONLY public.customer_reimbursements
    DROP CONSTRAINT IF EXISTS customer_reimbursements_series_id_fkey;
ALTER TABLE ONLY public.customer_reimbursements
    ADD CONSTRAINT customer_reimbursements_series_id_fkey
    FOREIGN KEY (series_id) REFERENCES public.customer_reimbursement_series(id) ON DELETE CASCADE;

ALTER TABLE ONLY public.customer_reimbursements
    DROP CONSTRAINT IF EXISTS customer_reimbursements_supersedes_id_fkey;
ALTER TABLE ONLY public.customer_reimbursements
    ADD CONSTRAINT customer_reimbursements_supersedes_id_fkey
    FOREIGN KEY (supersedes_id) REFERENCES public.customer_reimbursements(id) ON DELETE RESTRICT;

INSERT INTO settings(key,value)
VALUES ('postgresql_0313_customer_reimbursement_revisions','complete')
ON CONFLICT (key) DO UPDATE SET value=excluded.value;

COMMIT;
