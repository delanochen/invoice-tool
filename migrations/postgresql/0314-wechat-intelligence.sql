-- WeChat field intelligence: immutable evidence -> AI candidate -> human review.
CREATE TABLE IF NOT EXISTS public.wechat_raw_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_uid text NOT NULL UNIQUE,
    account_wxid text NOT NULL,
    chat_username text NOT NULL,
    chat_name text NOT NULL DEFAULT '',
    chat_type text NOT NULL DEFAULT 'group',
    local_id bigint,
    sort_seq bigint,
    shard text NOT NULL DEFAULT '',
    sender_wxid text NOT NULL DEFAULT '',
    sender_name text NOT NULL DEFAULT '',
    sender_attr text NOT NULL DEFAULT '',
    message_type text NOT NULL DEFAULT 'text',
    content text NOT NULL DEFAULT '',
    media_ref text,
    message_time text NOT NULL,
    raw_payload text NOT NULL DEFAULT '{}',
    received_at text NOT NULL,
    analysis_status text NOT NULL DEFAULT 'pending',
    analysis_error text
);

CREATE INDEX IF NOT EXISTS idx_wechat_raw_chat_time
    ON public.wechat_raw_messages (chat_username, message_time);
CREATE INDEX IF NOT EXISTS idx_wechat_raw_analysis
    ON public.wechat_raw_messages (analysis_status, message_time);

CREATE TABLE IF NOT EXISTS public.wechat_group_project_mappings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_username text NOT NULL UNIQUE,
    chat_name text NOT NULL DEFAULT '',
    service_order_id bigint REFERENCES public.service_orders(id) ON DELETE SET NULL,
    project_name text NOT NULL DEFAULT '',
    mapping_source text NOT NULL DEFAULT 'manual',
    confidence numeric(5,4),
    enabled boolean NOT NULL DEFAULT true,
    created_at text NOT NULL,
    updated_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.project_event_candidates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_uid text NOT NULL UNIQUE,
    service_order_id bigint REFERENCES public.service_orders(id) ON DELETE SET NULL,
    project_name text NOT NULL DEFAULT '',
    event_type text NOT NULL,
    title text NOT NULL,
    summary text NOT NULL DEFAULT '',
    event_time text,
    duration_minutes integer,
    responsibility text NOT NULL DEFAULT '',
    billing_relevance text NOT NULL DEFAULT 'unknown',
    status text NOT NULL DEFAULT 'pending',
    ai_confidence numeric(5,4),
    project_match_confidence numeric(5,4),
    ai_payload text NOT NULL DEFAULT '{}',
    reviewed_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    reviewed_at text,
    review_note text NOT NULL DEFAULT '',
    created_at text NOT NULL,
    updated_at text NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_project_event_candidates_review
    ON public.project_event_candidates (status, event_time);
CREATE INDEX IF NOT EXISTS idx_project_event_candidates_order
    ON public.project_event_candidates (service_order_id, event_time);

CREATE TABLE IF NOT EXISTS public.project_event_candidate_sources (
    candidate_id bigint NOT NULL REFERENCES public.project_event_candidates(id) ON DELETE CASCADE,
    message_id bigint NOT NULL REFERENCES public.wechat_raw_messages(id) ON DELETE RESTRICT,
    PRIMARY KEY (candidate_id, message_id)
);

CREATE TABLE IF NOT EXISTS public.technical_knowledge_candidates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    knowledge_uid text NOT NULL UNIQUE,
    service_order_id bigint REFERENCES public.service_orders(id) ON DELETE SET NULL,
    project_name text NOT NULL DEFAULT '',
    equipment text NOT NULL DEFAULT '',
    component text NOT NULL DEFAULT '',
    error_code text NOT NULL DEFAULT '',
    symptom text NOT NULL DEFAULT '',
    guidance text NOT NULL DEFAULT '',
    resolution text NOT NULL DEFAULT '',
    provenance_type text NOT NULL DEFAULT 'ai_inference',
    status text NOT NULL DEFAULT 'pending',
    ai_confidence numeric(5,4),
    ai_payload text NOT NULL DEFAULT '{}',
    reviewed_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    reviewed_at text,
    created_at text NOT NULL,
    updated_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.technical_knowledge_candidate_sources (
    candidate_id bigint NOT NULL REFERENCES public.technical_knowledge_candidates(id) ON DELETE CASCADE,
    message_id bigint NOT NULL REFERENCES public.wechat_raw_messages(id) ON DELETE RESTRICT,
    PRIMARY KEY (candidate_id, message_id)
);




-- WhatsApp identities are verified by a one-time code sent from the employee's
-- actual WhatsApp account.  wa_id is the durable identity used for authorization.
create table if not exists public.whatsapp_employee_identities (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    wa_id text not null unique,
    phone_number text,
    display_name text,
    verified_at text not null,
    enabled integer not null default 1,
    created_at text not null,
    updated_at text not null,
    unique (user_id)
);
create index if not exists idx_whatsapp_employee_identities_user
    on public.whatsapp_employee_identities(user_id, enabled);

create table if not exists public.whatsapp_binding_codes (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    code_hash text not null unique,
    expires_at text not null,
    consumed_at text,
    created_at text not null,
    created_by bigint references public.users(id) on delete set null
);
create index if not exists idx_whatsapp_binding_codes_user
    on public.whatsapp_binding_codes(user_id, expires_at);

create table if not exists public.whatsapp_messages (
    id bigint generated by default as identity primary key,
    meta_message_id text unique,
    wa_id text not null,
    direction text not null,
    message_type text not null,
    content text,
    media_id text,
    status text not null default 'received',
    raw_payload text not null default '{}',
    message_time text,
    created_at text not null
);
create index if not exists idx_whatsapp_messages_wa_time
    on public.whatsapp_messages(wa_id, message_time);

