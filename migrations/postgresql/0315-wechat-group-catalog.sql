-- Privacy-safe WeChat source discovery. Only group metadata is stored here;
-- message content still requires an enabled mapping in wechat_group_project_mappings.
CREATE TABLE IF NOT EXISTS public.wechat_group_catalog (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_username text NOT NULL UNIQUE,
    chat_name text NOT NULL DEFAULT '',
    account_wxid text NOT NULL DEFAULT '',
    first_seen_at text NOT NULL,
    last_seen_at text NOT NULL,
    updated_at text NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_wechat_group_catalog_name
    ON public.wechat_group_catalog (chat_name);

INSERT INTO settings(key,value)
VALUES ('postgresql_0315_wechat_group_catalog','complete')
ON CONFLICT (key) DO UPDATE SET value=excluded.value;

COMMIT;
