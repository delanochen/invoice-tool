-- Phase 1：多工单对一发票的关系表（只做兼容层，不改任何交互）
--
-- 目标：
--   * invoice_orders 记录"一张发票挂了哪些工单"，替代 invoices.service_order_id 的单列表达；
--   * 两个唯一索引分别表达"同一发票同一工单只出现一次"和"同一工单同时只能挂一张有效发票"，
--     后者由数据库在并发开票时兜底；
--   * invoice_items.service_order_id 保留单工单毛利归属。
--
-- 外键类型：以 PostgreSQL 实际列类型为准，invoices / service_orders / customer_reimbursements
-- 的主键都是 bigint（见 tests/schema_postgresql.sql），因此这里全部 bigint。
-- 作废发票也回填，但 released_at 有值：仍能反查到原工单，又不占用工单的重新开票资格。
--
-- 只做加法：不删列、不改既有索引、不迁移数据。
-- Apply only to invoice_test unless separately authorized by the user.
BEGIN;
SET LOCAL lock_timeout = '5s';

ALTER TABLE public.invoice_items
    ADD COLUMN IF NOT EXISTS service_order_id bigint;

CREATE TABLE IF NOT EXISTS public.invoice_orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    invoice_id bigint NOT NULL,
    service_order_id bigint NOT NULL,
    customer_reimbursement_id bigint,
    amount_cents bigint NOT NULL DEFAULT 0,
    released_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS invoice_orders_invoice_order_uidx
    ON public.invoice_orders (invoice_id, service_order_id);

-- 一个工单同时只能挂一张有效发票（released_at 为空即有效）。
CREATE UNIQUE INDEX IF NOT EXISTS invoice_orders_active_order_uidx
    ON public.invoice_orders (service_order_id)
    WHERE released_at IS NULL;

CREATE INDEX IF NOT EXISTS invoice_orders_invoice_idx
    ON public.invoice_orders (invoice_id);

-- 新表默认只有迁移执行角色可用：应用连接用的是独立角色（生产 invoice_app / 测试 invoice_test），
-- 不给授权的话开票写入会直接 permission denied。这里按存在性授权，避免写死角色名。
DO $$
DECLARE app_role text;
BEGIN
    FOREACH app_role IN ARRAY ARRAY['invoice_app', 'invoice_test'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = app_role) THEN
            EXECUTE format(
                'GRANT SELECT, INSERT, UPDATE, DELETE ON public.invoice_orders TO %I', app_role
            );
        END IF;
    END LOOP;
END $$;

COMMIT;
