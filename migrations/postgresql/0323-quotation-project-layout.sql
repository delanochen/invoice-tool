-- 兼容原则：
--   * 只新增列和 quotation_project_lines 表，不改既有行的金额、费率或条款；
--   * 已有报价单 layout 默认为 hourly，继续走 Time & Expense Quote Template v2；
--   * 幂等：ADD COLUMN IF NOT EXISTS / CREATE TABLE IF NOT EXISTS / 约束先删后加。

ALTER TABLE quotations ADD COLUMN IF NOT EXISTS layout text NOT NULL DEFAULT 'hourly';
ALTER TABLE quotations ADD COLUMN IF NOT EXISTS document_title text NOT NULL DEFAULT '';
ALTER TABLE quotations ADD COLUMN IF NOT EXISTS party_a text NOT NULL DEFAULT '';
ALTER TABLE quotations ADD COLUMN IF NOT EXISTS party_b text NOT NULL DEFAULT '';
ALTER TABLE quotations ADD COLUMN IF NOT EXISTS project_terms text NOT NULL DEFAULT '';
ALTER TABLE quotations ADD COLUMN IF NOT EXISTS include_standard_clauses integer NOT NULL DEFAULT 0;

ALTER TABLE quotations DROP CONSTRAINT IF EXISTS quotations_layout_check;
ALTER TABLE quotations ADD CONSTRAINT quotations_layout_check
    CHECK (layout IN ('hourly', 'project'));

ALTER TABLE quotations DROP CONSTRAINT IF EXISTS quotations_include_standard_clauses_check;
ALTER TABLE quotations ADD CONSTRAINT quotations_include_standard_clauses_check
    CHECK (include_standard_clauses IN (0, 1));

CREATE TABLE IF NOT EXISTS quotation_project_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id bigint NOT NULL REFERENCES quotations(id) ON DELETE CASCADE,
    sort_order integer NOT NULL,
    section_name text NOT NULL DEFAULT '',
    scope_of_work text NOT NULL DEFAULT '',
    qty numeric(14,4),
    unit text NOT NULL DEFAULT '',
    unit_price numeric(14,4),
    line_total numeric(14,2) NOT NULL DEFAULT 0,
    notes text NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_quotation_project_lines_quote
    ON quotation_project_lines(quotation_id, sort_order, id);

INSERT INTO settings(key, value)
VALUES ('postgresql_0323_quotation_project_layout', 'complete')
ON CONFLICT (key) DO UPDATE SET value = excluded.value;
